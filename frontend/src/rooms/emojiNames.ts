/** Emoji with and without the "show as a picture" marker are the same key. */
const bare = (e: string) => e.replace(/️/g, "");

export function emojiMatches(emoji: string, query: string): boolean {
  const q = query.trim().toLowerCase();
  if (!q) return true;
  if (emoji === query.trim()) return true;
  const words = NAMES[bare(emoji)];
  return !!words && q.split(/\s+/).every((part) => words.includes(part));
}
